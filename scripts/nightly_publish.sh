#!/usr/bin/env bash
# Nightly KB → site publish.
#
# Runs daily at 07:30 (after KB morning-brief at 06:30) via launchd plist
# com.lawrence.sotf-site.publish. Steps:
#   1. Source ~/.config/kb/env (PATH, ANTHROPIC_API_KEY etc.)
#   2. Activate the kb scripts venv (provides PyYAML etc.)
#   3. Run publish_kb.py — walks ~/kb/concepts/, filters, emits filtered markdown
#      to ~/projects/sotf-site/src/content/concepts/
#   4. Commit + push the snapshot to github.com/lawrencelundy/sotf-site
#   5. GitHub Action picks up the push, rebuilds, deploys to GitHub Pages
#
# Logs to ~/projects/sotf-site/logs/nightly-publish.log
#
# Safety (18 Oct 2026): on 16 Oct launchd fired the missed 07:30 run during a
# 2-second dark wake, the Mac slept, then restarted at 07:40; publish_kb.py had
# already wiped src/content/concepts and the tree was left with 3 of 778 pages.
# Now: the Python steps build in .publish-staging and swap only on success,
# caffeinate holds the Mac awake for the run, every failure or kill signal is
# logged with the step it hit, and the commit is refused if the staged concept
# count falls below 90% of HEAD's.
#
#   nightly_publish.sh            # full run: publish, commit, push (push = live deploy)
#   nightly_publish.sh --no-push  # publish + guards only; no commit, no push

set -euo pipefail

NO_PUSH=0
[ "${1:-}" = "--no-push" ] && NO_PUSH=1

# Site is served at the apex domain (stateofthefuture.io), so internal links
# resolve from root — publish with an empty base path, not the /sotf-site preview.
export SOTF_BASE=""

# Resolve from this script so a run from a worktree acts on that worktree.
SITE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG_DIR="$SITE_DIR/logs"
LOG_FILE="$LOG_DIR/nightly-publish.log"
mkdir -p "$LOG_DIR"

STEP="setup"
trap 'echo "FAILED at step \"$STEP\" (exit $?, line $LINENO) — nothing committed or pushed after this point" >> "$LOG_FILE"' ERR
trap 'echo "KILLED by signal during step \"$STEP\" — live content untouched (staged output discarded next run)" >> "$LOG_FILE"; exit 130' INT TERM HUP

# Hold off idle sleep for the life of this script (launchd can start us in a
# few-second dark wake; on 16 Oct the run froze 7 minutes after starting).
caffeinate -i -w $$ &

# shellcheck disable=SC1090
. "$HOME/.config/kb/env" 2>/dev/null || true

# Activate the kb venv (provides yaml, etc. for publish_kb.py)
# shellcheck disable=SC1091
. "$HOME/kb/scripts/.venv/bin/activate"

stamp=$(date '+%Y-%m-%d %H:%M:%S %Z')
echo "" >> "$LOG_FILE"
echo "=== $stamp — nightly publish ===" >> "$LOG_FILE"

# Step 1: emit filtered KB snapshot into the Astro content collection.
STEP="publish_kb.py"
python3 "$SITE_DIR/scripts/publish_kb.py" >> "$LOG_FILE" 2>&1

# Step 1a: Substack archive index (URL-verified, cached).
STEP="publish_writing.py"
python3 "$SITE_DIR/scripts/publish_writing.py" >> "$LOG_FILE" 2>&1

# Step 1b: members' edition → private R2 bucket. This IS the members' deploy
# (the Worker reads R2 on request), so it is skipped on --no-push like the git
# push is. Failure here must not block the public publish: log loudly, carry on.
STEP="upload_members.py"
if [ "$NO_PUSH" = 1 ]; then
  echo "--no-push: skipping members' R2 sync." >> "$LOG_FILE"
elif [ -z "${R2_ACCESS_KEY_ID:-}" ]; then
  echo "R2_ACCESS_KEY_ID not set (~/.config/kb/env) — members' content NOT synced." >> "$LOG_FILE"
elif ! python3 "$SITE_DIR/scripts/upload_members.py" >> "$LOG_FILE" 2>&1; then
  echo "MEMBERS SYNC FAILED — public publish continues; /members/ pages may be stale" >> "$LOG_FILE"
fi

# Step 2: stage + commit (only if there are real changes; git commit
#   --allow-empty=NO will exit 1 if nothing to commit — we treat that as success).
cd "$SITE_DIR"

# Push with retry: launchd at 07:30 sometimes runs before DNS/network is up
# ("Could not resolve host: github.com" — 10 failures, 19-28 Aug 2026, which left
# the live site 11 days stale). 3 attempts, 60s apart; a final failure is loud.
push_with_retry() {
  local attempt
  for attempt in 1 2 3; do
    if git push -q >> "$LOG_FILE" 2>&1; then
      return 0
    fi
    echo "push attempt $attempt failed; retrying in 60s" >> "$LOG_FILE"
    sleep 60
  done
  echo "PUSH FAILED after 3 attempts — site NOT deployed; commits remain local" >> "$LOG_FILE"
  return 1
}

# src/data/atlas.json is regenerated by publish_kb.py every run; it was never staged here,
# so the live Atlas froze at 31 Aug 2026 until this was added on 5 Oct 2026.
STEP="git add"
git add src/content/concepts src/content/writing src/data/atlas.json >> "$LOG_FILE" 2>&1

# Second guard, independent of the Python one: never commit a concept tree that
# has lost more than 10% of the pages in HEAD.
STEP="count guard"
head_count=$(git ls-tree -r --name-only HEAD -- src/content/concepts | grep -c '\.md$' || true)
staged_count=$(git ls-files -- src/content/concepts | grep -c '\.md$' || true)
echo "concept pages: $staged_count staged vs $head_count in HEAD" >> "$LOG_FILE"
if [ "$staged_count" -lt $(( head_count * 9 / 10 )) ]; then
  echo "ABORT: staged concept count $staged_count is below 90% of HEAD ($head_count); unstaging, nothing committed" >> "$LOG_FILE"
  git reset -q -- src/content/concepts src/content/writing src/data/atlas.json
  exit 3
fi

if [ "$NO_PUSH" = 1 ]; then
  git reset -q -- src/content/concepts src/content/writing src/data/atlas.json
  echo "--no-push: guards passed; changes left unstaged, nothing committed or pushed." >> "$LOG_FILE"
  exit 0
fi

if git diff --cached --quiet; then
  # Even with no new content, catch up any commits stranded by earlier push failures.
  if [ -n "$(git log --oneline @{u}..HEAD 2>/dev/null)" ]; then
    echo "No new changes, but unpushed commits found — pushing backlog." >> "$LOG_FILE"
    STEP="git push (backlog)"
    push_with_retry
  else
    echo "No changes since last publish — skipping commit + push." >> "$LOG_FILE"
  fi
  exit 0
fi

today=$(date '+%Y-%m-%d')
STEP="git commit"
git commit -q -m "Nightly KB publish — $today" >> "$LOG_FILE" 2>&1
STEP="git push"
push_with_retry
echo "Pushed snapshot. GitHub Action will rebuild + redeploy." >> "$LOG_FILE"
